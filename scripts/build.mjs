// Generates every platform output from tokens/*.json. Run with `npm run build`.
// Outputs are committed so consumers (Next.js via npm, Flutter via git) need no build step.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { ROOT, loadTokens, subtree, deriveBrands } from './lib.mjs';
import { symbolSvg, lockupSvg, lockupArabicSvg } from './logos.mjs';
import { previewHtml } from './preview.mjs';

const HEADER = 'Generated by unipal-brand/scripts/build.mjs from tokens/*.json. Do not edit by hand.';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const camel = (parts) =>
  parts
    .map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1)))
    .join('')
    .replace(/[^A-Za-z0-9]/g, '');

const fontStack = (list) => list.map((f) => (/[\s-]/.test(f) && !f.startsWith('-') ? `"${f}"` : f)).join(', ');

export function build() {
  const tokens = loadTokens();
  const color = subtree(tokens, 'color');
  const semantic = subtree(tokens, 'semantic');
  const font = subtree(tokens, 'font');
  const text = subtree(tokens, 'text');
  const space = subtree(tokens, 'space');
  const radius = subtree(tokens, 'radius');
  const shadow = subtree(tokens, 'shadow');
  const motion = subtree(tokens, 'motion');
  const brands = deriveBrands(tokens);
  const brandIds = Object.keys(brands);
  const defaultBrand = 'group';

  const files = {};

  // ---- CSS custom properties ---------------------------------------------------
  const paletteVars = [];
  for (const [path, { value, type }] of tokens) {
    if (type === 'color' && path.startsWith('color.')) {
      paletteVars.push(`  --up-${path.replace(/\./g, '-')}: ${value};`);
    }
  }
  const scaleVars = [
    ...Object.entries(font.family).map(([k, v]) => `  --up-font-${k}: ${fontStack(v)};`),
    ...Object.entries(font.weight).map(([k, v]) => `  --up-font-weight-${k}: ${v};`),
    ...Object.entries(font.size).map(([k, v]) => `  --up-font-size-${k}: ${v};`),
    ...Object.entries(font.lineHeight).map(([k, v]) => `  --up-line-height-${kebab(k)}: ${v};`),
    ...Object.entries(space).map(([k, v]) => `  --up-space-${k}: ${v};`),
    ...Object.entries(radius).map(([k, v]) => `  --up-radius-${k}: ${v};`),
    ...Object.entries(shadow).map(([k, v]) => `  --up-shadow-${k}: ${v};`),
    ...Object.entries(motion.duration).map(([k, v]) => `  --up-duration-${k}: ${v};`),
    ...Object.entries(motion.easing).map(([k, v]) => `  --up-easing-${k}: cubic-bezier(${v.join(', ')});`),
  ];
  const semanticVars = (mode) => Object.entries(semantic[mode]).map(([k, v]) => `  --up-${kebab(k)}: ${v};`);
  const brandVars = (id, mode) => Object.entries(brands[id][mode]).map(([k, v]) => `  --up-${kebab(k)}: ${v};`);
  const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;

  const darkBlocks = (rootSel, scopeSel) => [
    block(rootSel, [...semanticVars('dark'), ...brandVars(defaultBrand, 'dark'), '  color-scheme: dark;']),
    ...brandIds.map((id) =>
      block(`${rootSel}[data-brand="${id}"],\n${scopeSel} [data-brand="${id}"]`, brandVars(id, 'dark')),
    ),
  ];

  files['dist/css/tokens.css'] = [
    `/* ${HEADER} */`,
    '/* Set data-brand="group|advisors|tax|solutions" on <html> (or any element) to switch the accent.',
    '   Set data-theme="light|dark" on <html> to force a theme; otherwise it follows the system. */',
    '',
    block(':root', [...paletteVars, '', ...scaleVars, '', ...semanticVars('light'), ...brandVars(defaultBrand, 'light'), '  color-scheme: light;']),
    '',
    ...brandIds.map((id) => block(`[data-brand="${id}"]`, brandVars(id, 'light'))),
    '',
    '@media (prefers-color-scheme: dark) {',
    darkBlocks(':root:not([data-theme="light"])', ':root:not([data-theme="light"])')
      .join('\n')
      .replace(/^/gm, '  '),
    '}',
    '',
    ...darkBlocks(':root[data-theme="dark"]', ':root[data-theme="dark"]'),
    '',
  ].join('\n');

  // ---- Tailwind CSS v4 theme ------------------------------------------------------
  const twColor = [
    ...Object.keys(semantic.light).map((k) => `  --color-${kebab(k)}: var(--up-${kebab(k)});`),
    ...Object.keys(brands[defaultBrand].light).map((k) => `  --color-${kebab(k)}: var(--up-${kebab(k)});`),
    ...Object.keys(color.ink).map((k) => `  --color-ink-${k}: var(--up-color-ink-${k});`),
    ...Object.keys(color.sand).map((k) => `  --color-sand-${k}: var(--up-color-sand-${k});`),
    ...['copper', 'teal', 'plum', 'cobalt'].map((k) => `  --color-${k}: var(--up-color-${k});`),
  ];
  files['dist/css/theme.css'] = [
    `/* ${HEADER} */`,
    '/* Tailwind CSS v4: @import "tailwindcss"; @import "@unipal/brand/css/theme.css"; */',
    '@import "./tokens.css";',
    '',
    '@theme inline {',
    ...twColor,
    ...Object.keys(font.family).map((k) => `  --font-${k}: var(--up-font-${k});`),
    ...Object.keys(font.size).map((k) => `  --text-${k}: var(--up-font-size-${k});`),
    ...Object.keys(radius).filter((k) => k !== 'full').map((k) => `  --radius-${k}: var(--up-radius-${k});`),
    ...Object.keys(shadow).map((k) => `  --shadow-${k}: var(--up-shadow-${k});`),
    ...Object.keys(motion.easing).map((k) => `  --ease-${k}: var(--up-easing-${k});`),
    '}',
    '',
  ].join('\n');

  // ---- JavaScript / TypeScript ---------------------------------------------------
  const jsData = { color, semantic, font, text, space, radius, shadow, motion };
  files['dist/js/index.js'] = [
    `// ${HEADER}`,
    `export const tokens = ${JSON.stringify(jsData, null, 2)};`,
    '',
    `export const brands = ${JSON.stringify(brands, null, 2)};`,
    '',
    `export const brandIds = ${JSON.stringify(brandIds)};`,
    '',
    `export const defaultBrand = ${JSON.stringify(defaultBrand)};`,
    '',
    '/** Returns the brand whose domain matches a request host, falling back to the group brand. */',
    'export function brandForHost(host) {',
    "  // tax.unipal.group and staging-tax.unipal.group both map to tax; anything else to the group.",
    "  const bare = String(host ?? '').toLowerCase().split(':')[0].replace(/^www\\./, '');",
    "  const sub = bare.endsWith('.unipal.group') ? bare.split('.')[0].replace(/^staging-/, '') : '';",
    '  return brands[sub] ?? brands[defaultBrand];',
    '}',
    '',
  ].join('\n');

  const roleKeys = Object.keys(brands[defaultBrand].light);
  files['dist/js/index.d.ts'] = [
    `// ${HEADER}`,
    `export type BrandId = ${brandIds.map((id) => JSON.stringify(id)).join(' | ')};`,
    `export type BrandColors = { ${roleKeys.map((k) => `${k}: string`).join('; ')} };`,
    'export interface Brand {',
    '  id: BrandId;',
    '  name: string;',
    '  nameAr: string;',
    '  label: string;',
    '  labelAr: string;',
    '  domain: string;',
    '  light: BrandColors;',
    '  dark: BrandColors;',
    '}',
    `export declare const tokens: ${JSON.stringify(jsData, (k, v) => (typeof v === 'string' ? 'string' : typeof v === 'number' ? 0 : v), 2).replace(/"string"/g, 'string').replace(/: 0/g, ': number')};`,
    'export declare const brands: Record<BrandId, Brand>;',
    'export declare const brandIds: BrandId[];',
    'export declare const defaultBrand: BrandId;',
    'export declare function brandForHost(host: string | null | undefined): Brand;',
    '',
  ].join('\n');

  // ---- Dart / Flutter -------------------------------------------------------------
  const dartColor = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
  const px = (v) => String(v).replace('px', '');
  const dartNum = (v) => (String(px(v)).includes('.') ? px(v) : `${px(v)}.0`);
  const dartDuration = (v) => `Duration(milliseconds: ${parseInt(v, 10)})`;
  const dartString = (s) => `'${s.replace(/'/g, "\\'")}'`;
  const dartStringList = (list) => `[${list.map(dartString).join(', ')}]`;

  const paletteDart = [];
  for (const [path, { value, type }] of tokens) {
    if (type === 'color' && path.startsWith('color.')) {
      paletteDart.push(`  static const ${camel(path.split('.').slice(1))} = ${dartColor(value)};`);
    }
  }
  const semanticDart = (mode) =>
    Object.entries(semantic[mode]).map(([k, v]) => `    ${k}: ${dartColor(v)},`);
  const brandColorsDart = (id, mode) =>
    Object.entries(brands[id][mode]).map(([k, v]) => `      ${k}: ${dartColor(v)},`);

  files['flutter/lib/src/tokens.g.dart'] = [
    `// ${HEADER}`,
    '// ignore_for_file: constant_identifier_names',
    "import 'package:flutter/widgets.dart';",
    '',
    '/// Raw palette. Prefer [UnipalSemanticColors] and [UnipalBrandColors] in app code.',
    'abstract final class UnipalPalette {',
    ...paletteDart,
    '}',
    '',
    '/// Role-based colors for one theme mode.',
    'final class UnipalSemanticColors {',
    '  const UnipalSemanticColors({',
    ...Object.keys(semantic.light).map((k) => `    required this.${k},`),
    '  });',
    '',
    ...Object.keys(semantic.light).map((k) => `  final Color ${k};`),
    '',
    '  static const light = UnipalSemanticColors(',
    ...semanticDart('light'),
    '  );',
    '',
    '  static const dark = UnipalSemanticColors(',
    ...semanticDart('dark'),
    '  );',
    '}',
    '',
    '/// Accent roles for one brand in one theme mode.',
    'final class UnipalBrandColors {',
    '  const UnipalBrandColors({',
    ...roleKeys.map((k) => `    required this.${k},`),
    '  });',
    '',
    ...roleKeys.map((k) => `  final Color ${k};`),
    '}',
    '',
    '/// UniPal brands. Only the accent (the dot in the logo) differs between them.',
    'enum UnipalBrand {',
    ...brandIds.map((id) => {
      const b = brands[id];
      return [
        `  ${id}(`,
        `    displayName: ${dartString(b.name)},`,
        `    nameAr: ${dartString(b.nameAr)},`,
        `    label: ${dartString(b.label)},`,
        `    labelAr: ${dartString(b.labelAr)},`,
        `    domain: ${dartString(b.domain)},`,
        '    light: UnipalBrandColors(',
        ...brandColorsDart(id, 'light'),
        '    ),',
        '    dark: UnipalBrandColors(',
        ...brandColorsDart(id, 'dark'),
        '    ),',
        '  ),',
      ].join('\n');
    }),
    '  ;',
    '',
    '  const UnipalBrand({',
    '    required this.displayName,',
    '    required this.nameAr,',
    '    required this.label,',
    '    required this.labelAr,',
    '    required this.domain,',
    '    required this.light,',
    '    required this.dark,',
    '  });',
    '',
    '  final String displayName;',
    '  final String nameAr;',
    '  final String label;',
    '  final String labelAr;',
    '  final String domain;',
    '  final UnipalBrandColors light;',
    '  final UnipalBrandColors dark;',
    '}',
    '',
    'abstract final class UnipalFonts {',
    `  static const latin = ${dartString(font.family.latin[0])};`,
    `  static const arabic = ${dartString(font.family.arabic[0])};`,
    '  /// Readex Pro covers both Arabic and Latin; these are system fallbacks.',
    `  static const fallback = ${dartStringList(font.family.sans.slice(1))};`,
    '}',
    '',
    'abstract final class UnipalFontSize {',
    ...Object.entries(font.size).map(([k, v]) => `  static const ${/^\d/.test(k) ? `s${k}` : k} = ${dartNum(v)};`),
    '}',
    '',
    'abstract final class UnipalFontWeight {',
    ...Object.entries(font.weight).map(([k, v]) => `  static const ${k} = FontWeight.w${v};`),
    '}',
    '',
    'abstract final class UnipalLineHeight {',
    ...Object.entries(font.lineHeight).map(([k, v]) => `  static const ${k} = ${dartNum(v)};`),
    '}',
    '',
    'abstract final class UnipalSpace {',
    ...Object.entries(space).map(([k, v]) => `  static const s${k} = ${dartNum(v)};`),
    '}',
    '',
    'abstract final class UnipalRadius {',
    ...Object.entries(radius).map(([k, v]) => `  static const ${k} = ${dartNum(v)};`),
    '}',
    '',
    'abstract final class UnipalMotion {',
    ...Object.entries(motion.duration).map(([k, v]) => `  static const ${k} = ${dartDuration(v)};`),
    ...Object.entries(motion.easing).map(([k, v]) => `  static const ${k}Curve = Cubic(${v.map(dartNum).join(', ')});`),
    '}',
    '',
  ].join('\n');

  // ---- Logos ------------------------------------------------------------------------
  const ink = color.ink['900'];
  const paper = color.sand['50'];
  for (const id of brandIds) {
    const b = brands[id];
    const light = { ink, accent: b.light.accent, title: b.name };
    const dark = { ink: paper, accent: b.dark.accent, title: b.name };
    files[`logos/symbol-${id}.svg`] = symbolSvg(light);
    files[`logos/symbol-${id}-reversed.svg`] = symbolSvg(dark);
    files[`logos/lockup-${id}.svg`] = lockupSvg({ ...light, label: b.label });
    files[`logos/lockup-${id}-reversed.svg`] = lockupSvg({ ...dark, label: b.label });
    files[`logos/lockup-ar-${id}.svg`] = lockupArabicSvg({ ...light, labelAr: b.labelAr, labelColor: b.light.accentText });
    files[`logos/lockup-ar-${id}-reversed.svg`] = lockupArabicSvg({ ...dark, labelAr: b.labelAr, labelColor: b.dark.accentText });
  }

  // ---- Preview page ---------------------------------------------------------------------
  files['preview/index.html'] = previewHtml({
    css: files['dist/css/tokens.css'],
    brands,
    color,
    text,
    font,
    logos: Object.fromEntries(
      brandIds.map((id) => [
        id,
        {
          light: files[`logos/lockup-${id}.svg`],
          dark: files[`logos/lockup-${id}-reversed.svg`],
          arLight: files[`logos/lockup-ar-${id}.svg`],
          arDark: files[`logos/lockup-ar-${id}-reversed.svg`],
          symbol: files[`logos/symbol-${id}.svg`],
          symbolDark: files[`logos/symbol-${id}-reversed.svg`],
        },
      ]),
    ),
  });

  return files;
}

export function writeFiles(files) {
  for (const [rel, content] of Object.entries(files)) {
    const path = join(ROOT, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = build();
  writeFiles(files);
  console.log(`Wrote ${Object.keys(files).length} files.`);
}
